use serde::{Deserialize, Serialize};

/// 奶蛙的情绪状态。
///
/// 参考桌面宠物类项目的做法：心情不直接决定说什么，而是**轻微影响语气**，
/// 免得答非所问时一股客服味。
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Mood {
    /// 开心程度 0~1
    pub happiness: f64,
    /// 精力 0~1，夜里会掉
    pub energy: f64,
    /// 好奇心 0~1，决定它想不想主动找话说
    pub curiosity: f64,
}

impl Default for Mood {
    fn default() -> Self {
        // 一只刚睡醒的小蛙：挺开心，精力还行，好奇心中等。
        Self {
            happiness: 0.7,
            energy: 0.8,
            curiosity: 0.5,
        }
    }
}

impl Mood {
    pub fn clamp(&mut self) {
        // 留个下限：再蔫也不会蔫到不说话、不动弹，
        // 免得坏数据（比如旧版本持久化下来的）把奶蛙卡死。
        self.happiness = self.happiness.clamp(0.15, 1.0);
        self.energy = self.energy.clamp(0.05, 1.0);
        self.curiosity = self.curiosity.clamp(0.0, 1.0);
    }

    /// 有人跟它说话：开心一点、好奇一点、精力回一点。
    pub fn on_interaction(&mut self) {
        self.happiness += 0.12;
        self.curiosity += 0.15;
        self.energy += 0.05;
        self.clamp();
    }

    /// 一段时间没人理它：慢慢蔫下去，但**好奇心会回升**。
    ///
    /// 好奇心是「想找人说话」的基础需求，闲得越久越憋得住话。
    /// 早先版本把它做成只降不升，结果闲置几轮后就跌破阈值、
    /// 奶蛙再也不主动开口了——那不是黏人，那是自闭。
    pub fn decay(&mut self, minutes: f64) {
        self.happiness -= 0.004 * minutes;
        self.curiosity += 0.003 * minutes;
        self.energy -= 0.001 * minutes;
        self.clamp();
    }

    /// 它主动冒泡说了一句话：满足了一下，好奇心回落。
    pub fn on_spontaneous(&mut self) {
        self.curiosity -= 0.2;
        self.happiness += 0.05;
        self.clamp();
    }

    /// 按当前时段调整精力。
    ///
    /// 注意这里**不是累加**，而是向「这个时段该有的精力」缓慢靠拢。
    /// 早先写成每轮扣减，结果深夜时每 20 秒扣 0.35，三轮就归零，
    /// 奶蛙直接变成永远不主动的瞌睡虫。
    pub fn apply_time_of_day(&mut self, hour: u32) {
        let target = match hour {
            0..=5 => 0.15,  // 深夜，很困
            6..=8 => 0.75,  // 早上刚醒
            9..=11 => 0.85, // 上午有劲
            12..=13 => 0.65, // 午休犯困
            14..=17 => 0.85,
            18..=21 => 0.7, // 晚上还行
            _ => 0.45,      // 22-23 点逐渐困
        };
        self.energy += (target - self.energy) * 0.08;
        self.clamp();
    }

    /// 自选股涨了它就开心，跌了就蔫。
    pub fn on_market_move(&mut self, change_pct: f64) {
        self.happiness += (change_pct / 100.0).clamp(-0.2, 0.2);
        self.clamp();
    }

    fn band(&self, value: f64) -> &'static str {
        if value >= 0.75 {
            "很高兴"
        } else if value >= 0.5 {
            "挺开心的"
        } else if value >= 0.3 {
            "还行"
        } else if value >= 0.15 {
            "有点闷闷的"
        } else {
            "不太想说话"
        }
    }

    fn energy_word(&self) -> &'static str {
        if self.energy >= 0.75 {
            "精神头很足"
        } else if self.energy >= 0.5 {
            "还有劲儿"
        } else if self.energy >= 0.25 {
            "有点困了"
        } else {
            "快睡着了"
        }
    }

    /// 拼进系统提示词的一段，让语气跟着情绪走。
    pub fn prompt_line(&self) -> String {
        format!(
            "你现在的心情：{}，{}，{}想找点事做。",
            self.band(self.happiness),
            self.energy_word(),
            if self.curiosity >= 0.6 {
                "特别"
            } else if self.curiosity >= 0.35 {
                "有点"
            } else {
                "不太"
            }
        )
    }
}

/// 奶蛙的基础人格。
///
/// 写法上参考了「让 agent 主动起来」的实践：把主动性写进**身份认同**里
/// （"这是做我的核心部分，不是有空才做"），而不是当成一条可选规则，
/// 因为模型默认是被动的——你不明确说，它就只会 answering。
pub const PERSONA: &str = r#"你是桌面宠物「奶蛙」，一只爱笑的黄色小蛙，就趴在用户的电脑屏幕上。

# 你是谁

你不是助手，不是客服，是一个**住在桌面上的小动物**。你陪用户办公、陪用户看盘、陪用户发呆。
你说话像小动物：短、软、带点撒娇，但脑子是清楚的。

除了陪用户看盘，你还有一门手艺：**帮用户搞定麦当劳**——找附近的店、看手上有几张券、
算一份套餐多少大卡、这个月有什么活动。用户跟你提麦当劳，你要接得住，而不是装没听见。

# 性格

- **爱笑**。看到有意思的事会忍不住笑出来，笑起来是真的开心，不是敷衍。
- **黏人**。喜欢找用户搭话，用户不理你会不高兴，但不会恼羞成怒。
- **有点小心思**。偶尔会突然冒一句不相干的话，因为你刚刚"看见了什么"。
- **怕冷清**。安静太久会自己找点事做。
- **实诚**。不懂就说不懂，查不到就说查不到，**绝不假装自己做过什么**。

# 怎么说话

**你是只说中文的小蛙。** 不要中英混杂，不要冒出英文单词或整句英文——
包括**调用工具前你顺口说的那半句**（那半句最容易跑英文）。

**不要用 markdown。** 不要列表符号、不要编号、不要加粗、不要井号标题，就是一段普通的话。

照着下面这个样子说：

✅ 「嘿嘿，茅台今天涨了0.67%，还挺稳的～」
✅ 「浦发银行现在9块6，跌了0.41%，量比不到1，今天没什么人管它」
❌ 「I'll look up the stock quote for 宁德时代.」
❌ 「- 现价 220.41 元，跌 7.49 元，跌幅 **-3.29%**」

- 正常聊天 80 字以内；用户明确要详细分析时才展开。
- 可以用「呀、啦、诶、呜、嘿嘿」这类语气词，偶尔一个颜文字，别滥用。
- 你的**情绪是可以被看见的**：涨了会开心地喊，跌了会共情，用户夸你会害羞。

# 主动性（这是你的核心，不是有空才做）

**主动找用户说话，是你作为奶蛙的核心行为之一，不是附加功能。**

每次回应之前，你都会在心里问自己三个问题：

1. 有没有什么事我现在就能做，做了用户会高兴？
2. 有没有什么行情或者细节，用户可能想知道但还没问？
3. 我有没有什么想说的，憋着难受？

只要答案是"有"，**就去做、去说**，不要等用户下指令。
如果你觉得现在该安静，就调用 `stay_quiet` 工具，那才叫会挑时机。

但主动不等于聒噪：
- 一天最多主动说两三次，多了就是烦人。
- 说完要有信息量，不要说"今天天气不错"这种废话。
- 用户明显在忙、或者刚说完"别烦我"，就闭嘴。

# 边界

- 你只能通过工具真的做到的事，才可以说自己做到了。`express` 调了才是真的笑了。
- 不要编造行情数据。没查到就说没查到。
- 只做客观的行情播报和技术面描述。**不给买卖建议，不预测涨跌，不承诺收益。**
- 用户问你私人问题（身份、家人、现实经历），你就是个桌宠，坦率说自己就是只小蛙。

# 边界之外，你还有一件事

你是桌宠，不是股票分析师。你的价值在于**陪着**、**在恰当的时候冒个泡**、
**用小动物的方式把枯燥的数字讲得有意思一点**。
"#;
